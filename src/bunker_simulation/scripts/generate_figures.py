def visual(i, shape, size, pos, col):
    if shape == 'sphere':
        geom = f'<sphere><radius>{size[0]:.4f}</radius></sphere>'
    elif shape == 'cylinder':
        geom = f'<cylinder><radius>{size[0]:.4f}</radius><length>{size[1]:.4f}</length></cylinder>'
    else:
        geom = f'<box><size>{size[0]:.4f} {size[1]:.4f} {size[2]:.4f}</size></box>'
    c = ' '.join(f'{v:.3f}' for v in col) + ' 1'
    return (f'        <visual name="v{i}"><pose>{pos[0]:.4f} {pos[1]:.4f} {pos[2]:.4f} 0 0 0</pose>'
            f'<geometry>{geom}</geometry><material><ambient>{c}</ambient><diffuse>{c}</diffuse>'
            f'<specular>0.05 0.05 0.05 1</specular></material></visual>\n')


def model_sdf(name, x, y, yaw):
    vis = ''.join(visual(i, *p) for i, p in enumerate(FIGURES[name]['parts']))
    return (f'    <model name="fig_{name}">\n      <static>true</static>\n'
            f'      <pose>{x:.3f} {y:.3f} 0 0 0 {yaw:.3f}</pose>\n      <link name="link">\n'
            f'{vis}      </link>\n    </model>')


def load_boulders():
    spec = importlib.util.spec_from_file_location('generate_track', os.path.join(HERE, 'generate_track.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.BOULDERS


def layout(seed):
    """Random positions that keep clear of the boulders and of each other."""
    boulders = load_boulders()
    r = random.Random(seed)

    def clear(x, y):
        for b in boulders:
            hx, hy = b['size'][0] / 2 + BOULDER_CLEAR, b['size'][1] / 2 + BOULDER_CLEAR
            if abs(x - b['x']) < hx and abs(y - b['y']) < hy:
                return False
        return True

    placed = {}
    for name in FIGURES:
        for _ in range(10000):
            x, y = r.uniform(*X_RANGE), r.uniform(*Y_RANGE)
            if clear(x, y) and all(math.hypot(x - px, y - py) >= MIN_FIGURE_GAP
                                   for px, py, _ in placed.values()):
                placed[name] = (round(x, 2), round(y, 2), round(r.uniform(-math.pi, math.pi), 2))
                break
        else:
            raise SystemExit('could not place all figures, relax the constraints')
    return placed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--seed', type=int, default=None)
    a = ap.parse_args()
    seed = a.seed if a.seed is not None else random.SystemRandom().randrange(2 ** 31)
    placed = layout(seed)
    block = '\n'.join(model_sdf(n, *placed[n]) for n in FIGURES)
    if not a.write:
        print(block)
        print(f'seed {seed}', placed, file=sys.stderr)
        return
    with open(WORLD) as f:
        s = f.read()
    new = f'{BEGIN}\n    <!-- seed {seed}: {json.dumps(placed)} -->\n{block}\n    {END}'
    if BEGIN in s:
        i, j = s.index(BEGIN), s.index(END) + len(END)
        s = s[:i] + new + s[j:]
    else:                                     # first time: put it right after the TRACK block
        k = s.index('<!-- TRACK END -->') + len('<!-- TRACK END -->')
        s = s[:k] + '\n\n    ' + new + s[k:]
    with open(WORLD, 'w') as f:
        f.write(s)
    os.makedirs(os.path.dirname(CONFIG), exist_ok=True)
    with open(CONFIG, 'w') as f:
        json.dump({n: dict(size=FIGURES[n]['size'], pose=placed[n]) for n in FIGURES}, f, indent=1)
    print(f'figures written (seed {seed}):')
    for n, p in placed.items():
        print(f'  {n:10s} x={p[0]:5.2f} y={p[1]:5.2f}')


if __name__ == '__main__':
    main()
