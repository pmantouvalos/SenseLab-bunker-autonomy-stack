#!/usr/bin/env python3
"""
Generates the painted lane ("διάδρομος") of the demo and writes it into the world.

    python3 scripts/generate_lane.py            # print the SDF model
    python3 scripts/generate_lane.py --write    # replace the block between the
                                                # LANE BEGIN / LANE END markers
                                                # in worlds/cave_circuit_practice_01.sdf

Two continuous white lines, LANE_WIDTH apart, follow a centre line. With BEND = 0 (current
obstacle course) it is a straight lane; with BEND > 0 it bends gently to the left with a cosine
S-curve and is straight again:

    y_c(x) = 0                                        x <= X_BEND0
    y_c(x) = BEND/2 * (1 - cos(pi (x-X0)/(X1-X0)))    X_BEND0 < x < X_BEND1
    y_c(x) = BEND                                     x >= X_BEND1

Every line is a chain of thin boxes (visual only, no collision), so the robot drives
over them without noticing. Keep these numbers in sync with the artifacts in the world.
"""
import math
import os
import sys

# The floor of the starting area ends at x ~ 12.5 m (then there is a drop), so the lane must
# stay well before that.
X_START, X_END = -1.0, 11.0   # lane length (m)
LANE_WIDTH = 1.8              # distance between the two line centres (m)
LINE_WIDTH = 0.12             # painted line width (m)
X_BEND0, X_BEND1 = 3.0, 9.0   # where the curve starts / ends (m)
BEND = 0.0                    # sideways shift after the curve (m). 0 = straight lane (obstacle course)
STEP = 0.5                    # segment length (m)
THICK = 0.02                  # box height
Z_LINE = 0.03                 # centre height: the lines lie above the gravel bumps (see generate_track.py)


def centre(x):
    if x <= X_BEND0:
        return 0.0
    if x >= X_BEND1:
        return BEND
    t = (x - X_BEND0) / (X_BEND1 - X_BEND0)
    return BEND * 0.5 * (1.0 - math.cos(math.pi * t))


def segment(name, p0, p1):
    cx, cy = 0.5 * (p0[0] + p1[0]), 0.5 * (p0[1] + p1[1])
    length = math.hypot(p1[0] - p0[0], p1[1] - p0[1]) * 1.04  # tiny overlap, no gaps
    yaw = math.atan2(p1[1] - p0[1], p1[0] - p0[0])
    return f"""      <visual name="{name}">
        <pose>{cx:.4f} {cy:.4f} {Z_LINE} 0 0 {yaw:.5f}</pose>
        <geometry><box><size>{length:.4f} {LINE_WIDTH} {THICK}</size></box></geometry>
        <material>
          <ambient>1 1 1 1</ambient><diffuse>1 1 1 1</diffuse><specular>0.05 0.05 0.05 1</specular>
        </material>
      </visual>"""


def line_points(side):
    """side = +1 (left line) or -1 (right line). Offset along the local normal."""
    pts = []
    n = int(round((X_END - X_START) / STEP))
    for i in range(n + 1):
        x = X_START + i * STEP
        h = 1e-3
        slope = (centre(x + h) - centre(x - h)) / (2 * h)
        norm = math.hypot(1.0, slope)
        nx, ny = -slope / norm, 1.0 / norm  # left normal of the centre line
        pts.append((x + side * nx * LANE_WIDTH / 2, centre(x) + side * ny * LANE_WIDTH / 2))
    return pts


def build():
    out = ['    <model name="lane">', '      <static>true</static>', '      <link name="paint">']
    for side, label in ((+1, 'left'), (-1, 'right')):
        pts = line_points(side)
        for i in range(len(pts) - 1):
            out.append(segment(f'{label}_{i:02d}', pts[i], pts[i + 1]))
    out += ['      </link>', '    </model>']
    return '\n'.join(out)


def main():
    model = build()
    if '--write' not in sys.argv:
        print(model)
        return
    world = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'worlds',
                         'cave_circuit_practice_01.sdf')
    text = open(world).read()
    begin, end = '<!-- LANE BEGIN (generated by scripts/generate_lane.py) -->', '<!-- LANE END -->'
    if begin not in text or end not in text:
        sys.exit('LANE BEGIN / LANE END markers not found in the world file')
    head, rest = text.split(begin)
    _, tail = rest.split(end)
    open(world, 'w').write(f'{head}{begin}\n{model}\n    {end}{tail}')
    print(f'lane written to {os.path.normpath(world)}')


if __name__ == '__main__':
    main()
